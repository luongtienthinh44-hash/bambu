function bambu_register_polylang_strings() {
    if ( ! function_exists( 'pll_register_string' ) ) {
        return;
    }

    $strings = bambu_get_theme_translatable_strings();
    foreach ( $strings as $name => $item ) {
        pll_register_string( $name, $item['string'], 'Bambu Theme', ! empty( $item['multiline'] ) );
    }
}
add_action( 'init', 'bambu_register_polylang_strings' );

/**
 * Universal translation helper for Bambu theme.
 * Checks Polylang first, then Gettext / Loco Translate.
 */
function bambu_t( $string ) {
    if ( empty( $string ) || ! is_string( $string ) ) {
        return $string;
    }

    if ( function_exists( 'pll__' ) ) {
        $translated = pll__( $string );
        if ( $translated !== $string ) {
            return $translated;
        }
    }

    return __( $string, 'bambu' );
}
